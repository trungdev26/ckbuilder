import assert from 'node:assert/strict';
import { Script, WitnessArgs, hexFrom } from '@ckb-ccc/core';
const script = Script.from({ codeHash: '0x' + '11'.repeat(32), hashType: 'type', args: '0x1234' });
const encoded = script.toBytes();
const view = new DataView(encoded.buffer, encoded.byteOffset, encoded.byteLength);
const header = [0,4,8,12].map(offset => view.getUint32(offset,true));
assert.deepEqual(header,[55,16,48,49]);
assert.equal(view.getUint32(49,true),2);
assert.equal(Script.fromBytes(encoded).args,'0x1234');
const witness= WitnessArgs.from({lock:'0x1234'});
assert.equal(WitnessArgs.fromBytes(witness.toBytes()).lock,'0x1234');
const corrupted=encoded.slice();new DataView(corrupted.buffer).setUint32(8,9999,true);
assert.throws(()=>Script.fromBytes(corrupted));
console.log('Script fields: codeHash (32 bytes), hashType (1 byte), args (Bytes)');
console.log('Header [total size, field offsets]:',header);
console.log('Args byte count:',view.getUint32(49,true));
console.log('Encoded Script:',hexFrom(encoded));
console.log('Script and WitnessArgs round trips: PASS');
console.log('Out-of-bounds field offset rejected: PASS');
